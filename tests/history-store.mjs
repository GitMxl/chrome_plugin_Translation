import assert from 'node:assert/strict';
import { createHistoryStore, HISTORY_LIMIT } from '../history-store.js';
import { TARGET_LANGUAGES } from '../shared.js';
const saved = {};
const storage = { async get() { return JSON.parse(JSON.stringify(saved)); }, async set(value) { Object.assign(saved, value); } };
let counter = 0;
const history = createHistoryStore(storage, { makeId: () => `item-${++counter}`, now: () => counter });
const record = { source: 'Hello', translation: '你好', target: '简体中文', mode: 'local', engine: 'webllm' };
assert.equal((await history.list()).enabled, true);
await Promise.all(Array.from({ length: 10 }, (_, index) => history.add({ ...record, source: `Source ${index}` })));
assert.equal((await history.list()).total, 10, 'concurrent results must not overwrite one another');
await history.add({ ...record, source: 'Source 0', apiKey: 'must-never-be-saved', endpoint: 'https://secret.example', url: 'https://private.example' });
assert.equal((await history.list()).total, 10);
assert.equal((await history.list()).items[0].source, 'Source 0');
assert.equal(JSON.stringify(saved).includes('secret'), false);
assert.equal(JSON.stringify(saved).includes('private'), false);
assert.equal((await history.list('SOURCE 0')).items.length, 1);
assert.equal((await history.list('你好')).items.length, 10);
await history.setEnabled(false);
assert.equal(await history.add(record), false);
assert.equal((await history.list()).total, 10);
await history.setEnabled(true);
await assert.rejects(history.add({ ...record, source: 'x'.repeat(601) }));
await history.add({ ...record, source: '<img src=x onerror=alert(1)>' });
assert.equal((await history.list()).total, 11, 'a failed write must not poison future operations');
await history.remove((await history.list()).items[0].id);
assert.equal((await history.list()).total, 10);
for (let index = 0; index <= HISTORY_LIMIT; index++) await history.add({ ...record, source: `Entry ${index}` });
const bounded = await history.list();
assert.equal(bounded.total, HISTORY_LIMIT);
assert.equal(bounded.items[0].source, 'Entry 200');
assert.equal(bounded.items.at(-1).source, 'Entry 1');
await Promise.all([history.add(record), history.clear()]);
assert.equal((await history.list()).total, 0, 'clear must follow earlier pending writes');
assert.equal((await history.list()).enabled, true);
for (const language of TARGET_LANGUAGES.filter(language => language.code !== 'auto')) await history.add({ ...record, target: language.name });
assert.equal((await history.list()).total, TARGET_LANGUAGES.length - 1);
await assert.rejects(history.add({ ...record, target: 'Unrecognized language' }));
await history.clear();
console.log('PASS: local history concurrency, deduplication, bounds, search, deletion, clear, opt-out, invalid input recovery and secret exclusion.');
